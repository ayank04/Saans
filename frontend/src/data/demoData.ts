/* Search helper */
export function searchLocations(query: string): Array<{
  id: string;
  type: 'station' | 'ward';
  title: string;
  subtitle: string;
  aqi: number;
  category: AqiCategory;
  coordinates: [number, number];
}> {
  if (!query || query.trim().length === 0) return [];
  const q = query.toLowerCase().trim();

  const matchedStations = DEMO_STATIONS
    .filter(s => s.name.toLowerCase().includes(q) || s.area.toLowerCase().includes(q) || s.wardName.toLowerCase().includes(q))
    .map(s => ({
      id: s.id,
      type: 'station' as const,
      title: s.name,
      subtitle: `${s.area} • Station`,
      aqi: s.currentAqi,
      category: s.category,
      coordinates: [s.latitude, s.longitude] as [number, number]
    }));

  const matchedWards = DEMO_WARDS
    .filter(w => w.wardName.toLowerCase().includes(q) || w.bbmpZone.toLowerCase().includes(q))
    .map(w => ({
      id: `ward-${w.wardNumber}`,
      type: 'ward' as const,
      title: `${w.wardName} (Ward #${w.wardNumber})`,
      subtitle: `${w.bbmpZone} Zone • Ward`,
      aqi: w.averageAqi,
      category: w.category,
      // Approximate center
      coordinates: [12.9716, 77.5946] as [number, number]
    }));

  return [...matchedStations, ...matchedWards].slice(0, 8);
}
